fn busybox_image_bytes() -> &'static [u8] {
    unsafe {
        if let Some(bytes) = (*BUSYBOX_EXEC_BYTES.get()).as_ref() {
            return bytes;
        }
        let img = linux_rootfs::image().expect("m9 userspace rootfs");
        let busybox = img.lookup(b"/bin/busybox").expect("busybox");
        assert_eq!(busybox.kind, EntryKind::File);
        let bytes: &'static [u8] = busybox.data;
        *BUSYBOX_EXEC_BYTES.get() = Some(bytes);
        bytes
    }
}

/// The embedded BusyBox must be the pinned build (length + CRC32 recorded by `build.rs`
/// from the SHA-256-verified file) and must still be byte-identical at the end of the run.
fn verify_busybox_bytes(label: &str) {
    let bytes = busybox_image_bytes();
    let crc = clean_slate_rootfs::crc32(bytes);
    if bytes.len() != BUSYBOX_BYTES || crc != BUSYBOX_CRC32 {
        kernel_log_fmt(format_args!(
            "[M9  ] busybox drift {label} bytes={} crc32={crc:#010x} expected_bytes={BUSYBOX_BYTES} expected_crc32={BUSYBOX_CRC32:#010x}\n",
            bytes.len()
        ));
        fatal_kernel_error("m9 userspace busybox bytes drifted");
    }
    kernel_log_fmt(format_args!(
        "[M9  ] busybox {label} bytes={} crc32={crc:#010x} pinned_sha256={BUSYBOX_SHA256} rootfs_sha256={ROOTFS_IMAGE_SHA256}\n",
        bytes.len()
    ));
}

fn install_linux_stdio(pid: u64, generation: InstanceGeneration) {
    let personality = execution_personality_for_pid(pid)
        .unwrap_or_else(|_| fatal_kernel_error("m9 userspace personality"));
    if console_sink_render_style(personality) != ConsoleSinkRenderStyle::Verbatim {
        fatal_kernel_error("m9 userspace stdio not verbatim");
    }
    linux_fd::grant_console_stdio_for_process(pid, generation)
        .unwrap_or_else(|_| fatal_kernel_error("console stdio install"));
    let stdout = linux_fd::open_id_for_fd(pid, generation, 1)
        .unwrap_or_else(|_| fatal_kernel_error("console stdout description"));
    unsafe {
        *M9_STDOUT_OPEN.get() = Some(stdout);
    }
}

fn reset_command_evidence() {
    M9_STDOUT_LEN.store(0, Ordering::Relaxed);
    for counter in [
        &SLEEP.blocks,
        &SLEEP.woken,
        &SLEEP.timeouts,
        &SLEEP.cancelled,
        &SLEEP.woken_with_native_progress,
        &SLEEP.timeouts_with_native_progress,
        &OBJECT_READ_DENIALS,
        &OBJECT_WRITE_DENIALS,
        &NETWORK_DENIALS,
    ] {
        counter.store(0, Ordering::Relaxed);
    }
    SLEEP.native_steps_while_blocked.store(0, Ordering::Relaxed);
    SLEEP.max_blocked_ticks.store(0, Ordering::Relaxed);
}

fn launch_shell(
    allocator: &mut PageAllocator,
    name: &str,
    invocation: &[u8],
    authority: LinuxLaunchAuthority,
) {
    reset_command_evidence();
    let argv: [&[u8]; 3] = [b"/bin/sh", b"-c", invocation];
    let envp: [&[u8]; 1] = [b"PATH=/bin"];
    let spec = LinuxExecSpec {
        image: busybox_image_bytes(),
        argv: &argv,
        envp: &envp,
        exec_filename: b"/bin/sh",
        stack_pages: M9_BUSYBOX_STACK_PAGES,
        policy: &LINUX_CONVENTIONAL_LOAD_POLICY,
    };
    let (slot, stack_top) =
        pick_scheduler_slot_for_relaunch().unwrap_or_else(|m| fatal_kernel_error(m));
    let launched =
        launch_linux_process_with_authority(allocator, stack_top, slot, &spec, authority)
            .unwrap_or_else(|err| {
                kernel_log_fmt(format_args!(
                    "[M9  ] busybox launch err={}\n",
                    err.description()
                ));
                fatal_kernel_error("m9 userspace busybox launch failed");
            });
    if !LOW_VA_ENTRY_RANGE.contains(&launched.entry) {
        fatal_kernel_error("m9 userspace busybox entry outside the conventional low VA window");
    }
    install_linux_stdio(launched.pid, launched.instance_generation);
    M9_LINUX_PID.store(launched.pid, Ordering::Relaxed);
    kernel_log_fmt(format_args!(
        "[M9  ] shell started pid={} slot={} kstack=0x{:x} cmd={} cycle={} entry={:#x} net={} tmp={} stack_pages={}\n",
        launched.pid,
        slot,
        stack_top,
        name,
        cycle(),
        launched.entry,
        authority.network as u8,
        authority.tmp_objects as u8,
        M9_BUSYBOX_STACK_PAGES
    ));
}

fn spawn_native_sibling(allocator: &mut PageAllocator) {
    let stacks = unsafe { &*task_stacks_mut() };
    let native = spawn_native_userspace_process_with_code(
        allocator,
        task_stack_top(&stacks[NATIVE_SLOT]),
        &NATIVE_PROGRESS_CODE,
        NATIVE_PROCESS_STACK,
    )
    .unwrap_or_else(|_| fatal_kernel_error("native sibling"));
    configure_scheduler_thread_slot(NATIVE_SLOT, &native.thread)
        .unwrap_or_else(|_| fatal_kernel_error("native slot"));
}

/// Counts one native-sibling step (its `SYSCALL_NR_VERSION` loop).
pub(crate) fn observe_native_progress() {
    if unsafe { scheduler_mut() }.current_thread == Some(NATIVE_SLOT) {
        NATIVE_PROGRESS.fetch_add(1, Ordering::Relaxed);
    }
}

fn is_linux_pid(pid: u64) -> bool {
    matches!(
        execution_personality_for_pid(pid),
        Ok(ExecutionPersonality::LinuxX86_64)
    )
}

/// A Linux thread entered `ThreadState::Blocked`: remember the native step count.
pub(crate) fn on_thread_blocked(thread_index: usize, pid: u64) {
    if thread_index >= SCHEDULER_THREAD_SLOTS || !is_linux_pid(pid) {
        return;
    }
    SLEEP_NATIVE_AT_BLOCK[thread_index]
        .store(NATIVE_PROGRESS.load(Ordering::Relaxed), Ordering::Relaxed);
    SLEEP_TICKS_AT_BLOCK[thread_index].store(kernel_ticks(), Ordering::Relaxed);
    SLEEP_ARMED[thread_index].store(true, Ordering::Relaxed);
    SLEEP.blocks.fetch_add(1, Ordering::Relaxed);
}

/// A blocked thread became Ready (wake, deadline expiry, or cancel). Runs in IRQ or
/// syscall context: counters only.
pub(crate) fn on_thread_woken(thread_index: usize, outcome: WaitOutcome) {
    if thread_index >= SCHEDULER_THREAD_SLOTS
        || !SLEEP_ARMED[thread_index].swap(false, Ordering::Relaxed)
    {
        return;
    }
    let steps = NATIVE_PROGRESS
        .load(Ordering::Relaxed)
        .saturating_sub(SLEEP_NATIVE_AT_BLOCK[thread_index].load(Ordering::Relaxed));
    SLEEP
        .native_steps_while_blocked
        .fetch_add(steps, Ordering::Relaxed);
    let ticks =
        kernel_ticks().saturating_sub(SLEEP_TICKS_AT_BLOCK[thread_index].load(Ordering::Relaxed));
    SLEEP.max_blocked_ticks.fetch_max(ticks, Ordering::Relaxed);
    let (count, with_progress) = match outcome {
        WaitOutcome::Woken => (&SLEEP.woken, Some(&SLEEP.woken_with_native_progress)),
        WaitOutcome::TimedOut => (&SLEEP.timeouts, Some(&SLEEP.timeouts_with_native_progress)),
        WaitOutcome::Cancelled => (&SLEEP.cancelled, None),
    };
    count.fetch_add(1, Ordering::Relaxed);
    if let Some(with_progress) = with_progress.filter(|_| steps > 0) {
        with_progress.fetch_add(1, Ordering::Relaxed);
    }
}

pub(crate) fn observe_object_denial(write: bool) {
    let counter = if write {
        &OBJECT_WRITE_DENIALS
    } else {
        &OBJECT_READ_DENIALS
    };
    counter.fetch_add(1, Ordering::Relaxed);
}

