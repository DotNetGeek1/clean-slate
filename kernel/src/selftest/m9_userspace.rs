/// Kernel object occupancy; the reusable part must return to the baseline every cycle.
#[derive(Clone, Copy, PartialEq, Eq)]
struct Resources {
    linux_procs: usize,
    threads: usize,
    processes: usize,
    fd_tables: usize,
    open_files: usize,
    pipes: usize,
    linux_waiters: usize,
    sockets: usize,
    net_requests: usize,
    object_requests: usize,
    capabilities: usize,
    linux_mm: usize,
    linux_signals: usize,
    /// Persistent `/tmp` state: created in cycle 1 by the matrix, then reused.
    tmp_files: usize,
    fs_nodes: usize,
}

impl Resources {
    fn capture() -> Self {
        Self {
            linux_procs: table().occupied(),
            threads: unsafe { scheduler_mut() }.occupied_thread_slots(),
            processes: unsafe { process_registry_mut() }.occupied_slots(),
            fd_tables: linux_fd::fd_table_live_count(),
            open_files: usize::from(open_description_pool_live_count()),
            pipes: pool().live_count(),
            linux_waiters: waiter_occupancy_where(|pid| {
                !matches!(
                    execution_personality_for_pid(pid),
                    Ok(ExecutionPersonality::Native)
                )
            }),
            sockets: crate::process::linux_socket::pool_live_count(),
            net_requests: crate::service::net_bridge::net_bridge_mut().occupied_request_slots(),
            object_requests: crate::capability::object::object_queue_occupied_slots(),
            capabilities: crate::capability::live_capability_count(),
            linux_mm: linux_mem::occupied_slots(),
            linux_signals: crate::process::linux_signal::occupied_slots(),
            tmp_files: tmp_file_live_count(),
            fs_nodes: usize::from(crate::process::linux_fs::table().live_count()),
        }
    }

    fn log(&self, label: &str) {
        kernel_log_fmt(format_args!(
            "[M9  ] resources label={label} linux_procs={} threads={} processes={} fd_tables={} open_files={} pipes={} linux_waiters={} sockets={} net_requests={} object_requests={} capabilities={} linux_mm={} linux_signals={} tmp_files={} fs_nodes={} native_progress={}\n",
            self.linux_procs,
            self.threads,
            self.processes,
            self.fd_tables,
            self.open_files,
            self.pipes,
            self.linux_waiters,
            self.sockets,
            self.net_requests,
            self.object_requests,
            self.capabilities,
            self.linux_mm,
            self.linux_signals,
            self.tmp_files,
            self.fs_nodes,
            NATIVE_PROGRESS.load(Ordering::Relaxed),
        ));
    }

    fn reusable(&self) -> Self {
        Self {
            tmp_files: 0,
            fs_nodes: 0,
            ..*self
        }
    }
}

fn check_cycle_resources(cycle: u32) {
    let now = Resources::capture();
    now.log(if cycle == 1 { "cycle-1" } else { "cycle" });
    let baseline = unsafe { *BASELINE.get() }
        .unwrap_or_else(|| fatal_kernel_error("m9 userspace baseline missing"));
    if now.reusable() != baseline.reusable() {
        fatal_kernel_error("m9 userspace resource drift from baseline");
    }
    let first = unsafe { &mut *FIRST_CYCLE_RESOURCES.get() };
    match first {
        None => *first = Some(now),
        Some(first) if first.tmp_files != now.tmp_files || first.fs_nodes != now.fs_nodes => {
            fatal_kernel_error("m9 userspace persistent tmp state grew after cycle 1");
        }
        Some(_) => {}
    }
}

pub(crate) const fn fnv1a32(bytes: &[u8]) -> u32 {
    let mut hash = 0x811c_9dc5u32;
    let mut index = 0usize;
    while index < bytes.len() {
        hash ^= bytes[index] as u32;
        hash = hash.wrapping_mul(0x0100_0193);
        index += 1;
    }
    hash
}

fn stdout_slice() -> &'static [u8] {
    let len = M9_STDOUT_LEN.load(Ordering::Relaxed);
    let take = len.min(M9_STDOUT_CAP);
    unsafe {
        let buf = &*M9_STDOUT_BUF.get();
        core::slice::from_raw_parts(buf.as_ptr(), take)
    }
}

/// Captures bytes written through the open description installed as the checklist
/// shell's stdout (inherited across fork/dup), matching the reference harness's stdout
/// pipe; stderr diagnostics such as wget progress stay on the console only.
pub(crate) fn observe_console_description_write(open: OpenDescriptionId, bytes: &[u8]) {
    if unsafe { *M9_STDOUT_OPEN.get() } != Some(open) {
        return;
    }
    let len = M9_STDOUT_LEN.load(Ordering::Relaxed);
    let Some(end) = len
        .checked_add(bytes.len())
        .filter(|end| *end <= M9_STDOUT_CAP)
    else {
        fatal_kernel_error("m9 checklist stdout capture exceeded its bound");
    };
    unsafe {
        (&mut *M9_STDOUT_BUF.get())[len..end].copy_from_slice(bytes);
    }
    M9_STDOUT_LEN.store(end, Ordering::Relaxed);
}

fn log_stdout_hex(name: &str, out: &[u8]) {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    for (chunk_index, chunk) in out.chunks(STDOUT_HEX_CHUNK).enumerate() {
        let mut text = [0u8; STDOUT_HEX_CHUNK * 2];
        for (i, byte) in chunk.iter().enumerate() {
            text[i * 2] = HEX[usize::from(byte >> 4)];
            text[i * 2 + 1] = HEX[usize::from(byte & 0xF)];
        }
        let hex = core::str::from_utf8(&text[..chunk.len() * 2]).unwrap_or("?");
        kernel_log_fmt(format_args!(
            "[M9  ] stdout cmd={name} off={} hex={hex}\n",
            chunk_index * STDOUT_HEX_CHUNK
        ));
    }
}

fn contains(haystack: &[u8], needle: &[u8]) -> bool {
    needle.is_empty() || haystack.windows(needle.len()).any(|w| w == needle)
}

fn stdout_matches(cmd: &MatrixCommand, out: &[u8]) -> bool {
    cmd.stdout.is_none_or(|exact| out == exact)
        && cmd
            .stdout_prefix
            .is_none_or(|prefix| out.starts_with(prefix))
        && cmd
            .stdout_contains
            .iter()
            .all(|needle| contains(out, needle))
}

fn finish_matrix_command(index: usize, status: u64) {
    let cmd = &M9_COMMAND_MATRIX[index];
    let cycle = cycle();
    let out = stdout_slice();
    let fnv = fnv1a32(out);
    kernel_log_fmt(format_args!(
        "[M9  ] cmd={} cycle={cycle} status={status} stdout_len={} fnv=0x{fnv:08x}\n",
        cmd.name,
        out.len()
    ));
    log_sleep_stats(cmd.name);
    if status != u64::from(cmd.exit_status) {
        fatal_kernel_error("m9 userspace command exit status");
    }
    if proc_table_invariant_violations() > 0 {
        fatal_kernel_error("m9 userspace proc-table invariant");
    }
    let first = unsafe { &mut (*FIRST_CYCLE_STDOUT.get())[index] };
    if cycle == 1 {
        log_stdout_hex(cmd.name, out);
        if !stdout_matches(cmd, out) {
            fatal_kernel_error("m9 userspace command stdout differs from commands.toml");
        }
        *first = (out.len(), fnv);
    } else if *first != (out.len(), fnv) {
        fatal_kernel_error("m9 userspace command stdout changed across reuse cycles");
    }
    if cycle != 1 {
        return;
    }
    match cmd.name {
        "tmp-file-io" => kernel_log_line("[M9  ] fs PASS"),
        "pipe-grep" => kernel_log_line("[M9  ] process-pipe PASS"),
        "nslookup-fixture" => {
            kernel_log_line("[M9  ] dns PASS");
            let woken = SLEEP.woken_with_native_progress.load(Ordering::Relaxed);
            let ticks = SLEEP.max_blocked_ticks.load(Ordering::Relaxed);
            if woken == 0 || ticks == 0 {
                fatal_kernel_error("m9 userspace DNS wait never slept while native work ran");
            }
            kernel_log_fmt(format_args!(
                "[M9  ] blocking PASS cmd={} woken_with_native_progress={woken} native_steps_while_blocked={} max_blocked_ticks={ticks}\n",
                cmd.name,
                SLEEP.native_steps_while_blocked.load(Ordering::Relaxed)
            ));
        }
        "wget-fixture-http" => kernel_log_line("[M9  ] tcp PASS"),
        _ => {}
    }
}

fn finish_probe(index: usize, pid: u64, status: u64) {
    let probe = &PROBES[index];
    let read_denials = OBJECT_READ_DENIALS.load(Ordering::Relaxed);
    let write_denials = OBJECT_WRITE_DENIALS.load(Ordering::Relaxed);
    let net_denials = NETWORK_DENIALS.load(Ordering::Relaxed);
    kernel_log_fmt(format_args!(
        "[M9  ] probe={} cycle={} pid={pid} status={status} object_read_denials={read_denials} object_write_denials={write_denials} network_denials={net_denials} stdout_len={}\n",
        probe.name,
        cycle(),
        stdout_slice().len()
    ));
    log_sleep_stats(probe.name);
    if status != probe.exit_status {
        fatal_kernel_error("m9 userspace probe exit status");
    }
    if !stdout_slice().is_empty() {
        fatal_kernel_error("m9 userspace probe wrote to stdout");
    }
    let proven = match probe.evidence {
        ProbeEvidence::ReadOnlyProjection => {
            read_denials == 0 && write_denials == 0 && net_denials == 0
        }
        ProbeEvidence::TmpWriteDenied => write_denials > 0 && net_denials == 0,
        ProbeEvidence::TmpReadDenied => read_denials > 0 && write_denials == 0,
        ProbeEvidence::NetworkDenied => net_denials > 0 && read_denials + write_denials == 0,
        ProbeEvidence::ConnectTimeout => {
            SLEEP.woken_with_native_progress.load(Ordering::Relaxed) > 0
                && SLEEP.max_blocked_ticks.load(Ordering::Relaxed)
                    >= CONNECT_TIMEOUT_MIN_BLOCKED_TICKS
        }
    };
    if !proven {
        fatal_kernel_error("m9 userspace probe evidence missing");
    }
    match probe.evidence {
        ProbeEvidence::TmpReadDenied => kernel_log_line("[M9  ] deny fs ok"),
        ProbeEvidence::NetworkDenied => kernel_log_line("[M9  ] deny net ok"),
        ProbeEvidence::ConnectTimeout if cycle() == 1 => {
            kernel_log_fmt(format_args!(
                "[M9  ] timeout PASS cmd={} woken_with_native_progress={} native_steps_while_blocked={} max_blocked_ticks={}\n",
                probe.name,
                SLEEP.woken_with_native_progress.load(Ordering::Relaxed),
                SLEEP.native_steps_while_blocked.load(Ordering::Relaxed),
                SLEEP.max_blocked_ticks.load(Ordering::Relaxed)
            ));
        }
        _ => {}
    }
}

fn dispatch_phase(allocator: &mut PageAllocator) {
    match phase() {
        Phase::Command(index) => {
            let cmd = &M9_COMMAND_MATRIX[index];
            launch_shell(
                allocator,
                cmd.name,
                cmd.invocation,
                LinuxLaunchAuthority::FULL,
            );
        }
        Phase::Probe(index) => {
            let probe = &PROBES[index];
            launch_shell(allocator, probe.name, probe.invocation, probe.authority);
        }
    }
}

fn finish_run() -> ! {
    verify_busybox_bytes("intact");
    kernel_log_line("[M9  ] denial PASS");
    kernel_log_line(PASS_MARKER);
    qemu_exit(QEMU_EXIT_SUCCESS)
}

/// Record a checklist-shell fault; [`checklist_fault_pending`] runs after teardown.
pub(crate) fn on_checklist_command_fault(pid: u64, context: &InterruptContext) {
    if pid != M9_LINUX_PID.load(Ordering::Relaxed) {
        return;
    }
    let name = match phase() {
        Phase::Command(index) => M9_COMMAND_MATRIX[index].name,
        Phase::Probe(index) => PROBES[index].name,
    };
    let cr2 = if context.vector as usize == 14 {
        x86_64::registers::control::Cr2::read()
            .map(|a| a.as_u64())
            .unwrap_or(0)
    } else {
        0
    };
    kernel_log_fmt(format_args!(
        "[M9  ] checklist fault cmd={name} vector={} rip={:#018x} cr2={cr2:#018x}\n",
        context.vector, context.rip
    ));
    if let Some(gen) = live_instance_generation(pid) {
        linux_mem::log_m9_exec_layout(pid, gen, cr2);
    }
    M9_CHECKLIST_FAULT.store(true, Ordering::SeqCst);
}

pub(crate) fn checklist_fault_pending() -> bool {
    M9_CHECKLIST_FAULT.load(Ordering::SeqCst)
}

pub(crate) fn after_linux_exit_group(
    pid: u64,
    teardown: &DomainTeardownResult,
    allocator: &mut PageAllocator,
) -> Option<u64> {
    if pid != M9_LINUX_PID.load(Ordering::Relaxed) {
        return None;
    }
    let next = match phase() {
        Phase::Command(index) => {
            finish_matrix_command(index, teardown.exit_status);
            if index + 1 < MATRIX_LEN {
                Phase::Command(index + 1)
            } else {
                Phase::Probe(0)
            }
        }
        Phase::Probe(index) => {
            finish_probe(index, pid, teardown.exit_status);
            if index + 1 < PROBES.len() {
                Phase::Probe(index + 1)
            } else {
                let finished = cycle();
                check_cycle_resources(finished);
                kernel_log_fmt(format_args!("[M9  ] cycle={finished}\n"));
                if finished >= USERSPACE_CYCLES {
                    finish_run();
                }
                M9_CYCLE.store(finished + 1, Ordering::Relaxed);
                Phase::Command(0)
            }
        }
    };
    set_phase(next);
    dispatch_phase(allocator);
    Some(start_current_scheduler_thread().unwrap_or_else(|m| fatal_kernel_error(m)))
}

fn launch_storage_service(
    controller: &mut ServiceLifecycleController,
    allocator: &mut PageAllocator,
    lifecycle_capability: u64,
) {
    let result = controller
        .handle_control_message(
            allocator,
            SUPERVISOR_PID,
            lifecycle_capability,
            &LifecycleMessage::ControlRequest(ControlRequest::new(
                STORAGE_SERVICE_ID,
                ControlRequestKind::Start,
            ))
            .encode(),
        )
        .unwrap_or_else(|_| fatal_kernel_error("m9 userspace storage launch failed"));
    let pid = result
        .event
        .map(|event| event.instance.pid.0)
        .unwrap_or_else(|| fatal_kernel_error("storage pid missing"));
    kernel_log_fmt(format_args!("[STOR] object-service started pid={pid}\n"));
}

fn launch_network_service(
    controller: &mut ServiceLifecycleController,
    allocator: &mut PageAllocator,
    lifecycle_capability: u64,
) {
    let _ = controller
        .handle_control_message(
            allocator,
            SUPERVISOR_PID,
            lifecycle_capability,
            &LifecycleMessage::ControlRequest(ControlRequest::new(
                NETWORK_SERVICE_ID,
                ControlRequestKind::Start,
            ))
            .encode(),
        )
        .unwrap_or_else(|_| fatal_kernel_error("m9 userspace network launch failed"));
}

pub(crate) fn start_m9_userspace_self_test(page_allocator: PageAllocator) -> ! {
    kernel_log_line("[M9  ] creating");
    install_service_lifecycle_syscall_allocator(page_allocator);
    reset_process_scheduler_world();
    unsafe {
        *id_allocator_mut() = IdAllocator::new();
        process_registry_mut().clear();
        *scheduler_mut() = Scheduler::new();
    }
    linux_fd::reset_registry_for_selftest();

    let img = linux_rootfs::image().expect("rootfs");
    crate::process::linux_fs::init_namespace(&img).expect("namespace");
    linux_rootfs::ensure_rootfs_integrity_logged().expect("integrity");
    verify_busybox_bytes("verified");
    kernel_log_fmt(format_args!(
        "[M9  ] matrix commands={MATRIX_LEN} probes={} cycles={USERSPACE_CYCLES}\n",
        PROBES.len()
    ));
    for cmd in M9_COMMAND_MATRIX {
        if let Some((path, body)) = cmd.stage {
            bootstrap_tmp_file_bytes(path, body)
                .unwrap_or_else(|_| fatal_kernel_error("m9 userspace stage file"));
        }
    }

    let allocator = allocator();
    let kernel_root = current_root_frame_address();
    let kernel_stack_top = unsafe { task_stack_top(&(*task_stacks_mut())[0]) };
    set_privilege_stack(kernel_stack_top).unwrap_or_else(|m| fatal_kernel_error(m));
    initialize_syscall_abi(kernel_stack_top).unwrap_or_else(|m| fatal_kernel_error(m));

    let controller = unsafe { service_lifecycle_controller_mut() };
    controller.clear();
    controller.configure_launch_context(kernel_root);
    controller
        .declare_service(STORAGE_SERVICE_ID)
        .unwrap_or_else(|m| fatal_kernel_error(m));
    controller
        .declare_service(NETWORK_SERVICE_ID)
        .unwrap_or_else(|m| fatal_kernel_error(m));
    let lifecycle_capability = controller
        .grant_lifecycle_control_capability(SUPERVISOR_PID)
        .unwrap_or_else(|m| fatal_kernel_error(m));

    launch_storage_service(controller, allocator, lifecycle_capability);
    crate::selftest::m7_net_service::init_minimal_state_for_m9_socket(lifecycle_capability);
    launch_network_service(controller, allocator, lifecycle_capability);
    crate::process::linux_socket::grant_linux_network_capabilities(SUPERVISOR_PID)
        .unwrap_or_else(|_| fatal_kernel_error("network grant"));

    spawn_native_sibling(allocator);
    let baseline = Resources::capture();
    baseline.log("baseline");
    unsafe { *BASELINE.get() = Some(baseline) };

    initialize_timer();
    // `m3-entry-self-test` skips calibration inside `initialize_timer`; the net service's
    // WAIT_WORK/RX deadlines and Linux `nanosleep` use TSC `MonotonicNs` deadlines.
    crate::time::calibration::calibrate_apic_tick();
    kernel_log_line("[TIME] timer initialized");

    set_phase(Phase::Command(0));
    dispatch_phase(allocator);
    let frame = start_current_scheduler_thread().unwrap_or_else(|m| fatal_kernel_error(m));
    unsafe { restore_task_context(frame) }
}
