/// What a probe must demonstrate besides its exit status.
#[derive(Clone, Copy, PartialEq, Eq)]
enum ProbeEvidence {
    /// Write outside the writable `/tmp` projection: `EROFS` from the namespace, no
    /// capability denial involved.
    ReadOnlyProjection,
    /// `/tmp` mutation without the projection grant: capability-layer `op=write` denial.
    TmpWriteDenied,
    /// `/tmp` read without object authority: capability-layer `op=read` denial.
    TmpReadDenied,
    /// `socket(2)` without network authority: `[NET ] denied ... reason=no-authority`.
    NetworkDenied,
    /// Connect to an address the hermetic fixture never answers: the network service's
    /// deadline-driven SYN retransmission gives up and wakes the blocked caller with
    /// `ETIMEDOUT` (checked by the host from BusyBox's stderr).
    ConnectTimeout,
}

